"""
Agent registry, data model, config, and pipeline orchestration.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Dict, List, Optional
import logging

logger = logging.getLogger(__name__)


class Severity(str, Enum):
    CRITICAL = "critical"
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"
    INFO = "info"


class Blocker(str, Enum):
    BLOCKS = "blocks"
    WARNS = "warns"
    ALLOWS = "allows"


@dataclass
class Finding:
    agent: str
    severity: Severity
    category: str
    message: str
    file: str
    line: Optional[int] = None
    suggestion: Optional[str] = None
    suggested_code: Optional[str] = None
    blocker: Blocker = Blocker.BLOCKS
    auto_fixable: bool = False
    confidence: float = 1.0
    rule_id: Optional[str] = None
    # Other agents that raised the same issue. Populated by dedupe_results();
    # empty for a finding nothing else corroborated.
    corroborated_by: List[str] = field(default_factory=list)


@dataclass
class AgentResult:
    agent_name: str
    findings: List[Finding] = field(default_factory=list)
    passed: bool = True
    duration_ms: float = 0.0

    @property
    def blocking_findings(self) -> List[Finding]:
        return [f for f in self.findings if f.blocker == Blocker.BLOCKS]


class BaseAgent:
    name: str = "base"
    description: str = "Base agent"

    def review(self, file_path: str, content: str, diff: str,
               skeleton: str = "", line_count: int = None,
               fast: bool = False) -> AgentResult:
        import time
        start = time.time()
        findings = self._check(file_path, content, diff, skeleton, line_count, fast)
        duration = (time.time() - start) * 1000
        blocking = any(f.blocker == Blocker.BLOCKS for f in findings)
        return AgentResult(
            agent_name=self.name,
            findings=findings,
            passed=not blocking,
            duration_ms=duration,
        )

    def _check(self, file_path: str, content: str, diff: str,
               skeleton: str = "", line_count: int = None,
               fast: bool = False) -> List[Finding]:
        raise NotImplementedError


AGENT_REGISTRY: Dict[str, BaseAgent] = {}


def register_agent(cls: BaseAgent) -> BaseAgent:
    AGENT_REGISTRY[cls.name] = cls()
    return cls


def get_agent(name: str) -> Optional[BaseAgent]:
    return AGENT_REGISTRY.get(name)


def list_agents() -> List[str]:
    return list(AGENT_REGISTRY.keys())


def run_pipeline(agents: List[str], file_path: str, content: str,
                 diff: str, skeleton: str = "",
                 line_count: int = None, fast: bool = False) -> List[AgentResult]:
    results = []
    for agent_name in agents:
        agent = get_agent(agent_name)
        if agent is None:
            logger.warning("Agent %s not found, skipping", agent_name)
            continue
        result = agent.review(file_path, content, diff, skeleton, line_count, fast)
        results.append(result)
    return results


def risk_score(file_path: str, content: str, diff: str, findings=None) -> float:
    """Score 0.0 (low risk) to 1.0 (high risk) for a file.

    Combines file characteristics with the severity of what was actually
    found: a tiny file with a critical finding is high risk, so a 0.0 score
    next to a blocking finding (which read as a contradiction to CI
    consumers) cannot happen any more.
    """
    score = 0.0
    name = file_path.lower()

    if any(k in name for k in ["config", "secret", "env", "credential", "key", "auth"]):
        score += 0.3

    diff_lines = diff.count("\n")
    if diff_lines > 200:
        score += 0.3
    elif diff_lines > 50:
        score += 0.15

    if any(m in content.lower() for m in ["generated by", "copilot", "chatgpt", "claude"]):
        score += 0.2

    if "test" in name or "spec" in name:
        score -= 0.2

    if file_path.endswith((".md", ".rst", ".txt", ".yaml", ".yml", ".json")):
        score -= 0.1

    weight = {Severity.CRITICAL: 0.25, Severity.HIGH: 0.1,
              Severity.MEDIUM: 0.03, Severity.LOW: 0.0, Severity.INFO: 0.0}
    for f in findings or []:
        score += weight.get(f.severity, 0.0)

    return round(max(0.0, min(1.0, score)), 2)


def quality_gates_met(results: List[AgentResult], config: dict) -> bool:
    """Check if all quality gates pass.

    Only high and critical findings block the commit (the ``block_on`` set).
    A blocking finding means the change is not safe to commit, so it fails the
    gate as well; otherwise ``quality_gates_passed`` could be true while the
    review is blocked, which reads as a contradiction in JSON output.

    The regex quality agent reports advisory rules as LOW/MEDIUM with
    ``Blocker.WARNS``; those never block regardless of the gate thresholds, so
    a style preference cannot stop a commit.
    """
    gates = config.get("quality_gates", {})
    blocking_sev = set(config.get("block_on", ["critical", "high"]))
    all_findings = [f for r in results for f in r.findings]

    for f in all_findings:
        if f.blocker == Blocker.BLOCKS and f.severity.value in blocking_sev:
            return False

    max_complexity = gates.get("max_complexity")
    if max_complexity:
        for f in all_findings:
            if (f.category == "Complexity"
                    and f.severity.value in blocking_sev):
                return False

    max_file_length = gates.get("max_file_length")
    if max_file_length:
        for f in all_findings:
            if (f.category == "File Length"
                    and f.severity.value in blocking_sev):
                return False

    min_coverage = gates.get("min_coverage")
    if min_coverage:
        for f in all_findings:
            if (f.category == "Missing Tests"
                    and f.severity.value in blocking_sev):
                return False

    return True